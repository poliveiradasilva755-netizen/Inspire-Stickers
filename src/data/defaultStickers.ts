function slugifyId(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function buildDefaultStickers(): StickerItem[] {
  const result: StickerItem[] = [];
  let globalIndex = 0;

  (Object.keys(CATEGORY_SEEDS) as StickerCategoryName[]).forEach((category, catIdx) => {
    const config = CATEGORY_SEEDS[category];
    const baseEntries = config.entries;

    for (let idx = 0; idx < config.targetCount; idx++) {
      const baseIndex = idx % baseEntries.length;
      const cycle = Math.floor(idx / baseEntries.length);
      const [primary, baseSecondary, specificTags, explicitPreset, explicitSymbol] =
        baseEntries[baseIndex];

      let preset: EditorialPreset;
      let secondary: string;
      let symbol: AccentSymbol;
      let displayName: string;

      const baseTitle = primary.charAt(0).toUpperCase() + primary.slice(1);

      if (cycle === 0) {
        preset = explicitPreset || PRESET_ROTATION[(idx + catIdx) % PRESET_ROTATION.length];
        secondary = baseSecondary;
        symbol =
          explicitSymbol || config.defaultSymbols[(idx + catIdx) % config.defaultSymbols.length];
        displayName = baseTitle;
      } else {
        // Choose a visually distinct layout preset, subtitle, and ornament for each additional edition
        const altPreset =
          config.altPresets[(idx + cycle * 3 + catIdx) % config.altPresets.length];
        preset = altPreset === explicitPreset
          ? config.altPresets[(idx + cycle * 3 + catIdx + 1) % config.altPresets.length]
          : altPreset;

        secondary =
          preset === 'checklist-card'
            ? baseSecondary.includes('|')
              ? baseSecondary
              : `${config.defaultTags[0] || 'Foco'}|${config.defaultTags[1] || 'Paz'}|${config.defaultTags[2] || 'Amor'}`
            : config.altSubtitles[(idx + cycle * 2) % config.altSubtitles.length];

        symbol = config.defaultSymbols[(idx + cycle) % config.defaultSymbols.length];

        const suffix =
          config.editionSuffixes[(idx + cycle) % config.editionSuffixes.length];
        displayName = `${baseTitle} · ${suffix}`;
      }

      const mergedTags = Array.from(
        new Set([...specificTags, ...config.defaultTags])
      );

      const dayOffset = String(1 + (idx % 28)).padStart(2, '0');
      const monthOffset = String(1 + ((catIdx + cycle) % 12)).padStart(2, '0');

      result.push({
        id: `${slugifyId(category)}-${idx + 1}-${slugifyId(primary).slice(0, 16)}`,
        name: displayName,
        category,
        tags: mergedTags,
        preset,
        primaryText: primary,
        secondaryText: secondary,
        tertiaryText: String((idx + catIdx) % 7),
        accentSymbol: symbol,
        featured: idx < 2,
        createdAt: `2026-${monthOffset}-${dayOffset}`,
        copyCount: 110 + ((globalIndex * 41 + idx * 17) % 480),
      });
      globalIndex++;
    }
  });

  return result;
}

export const DEFAULT_STICKERS: StickerItem[] = buildDefaultStickers();
